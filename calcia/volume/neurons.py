def _ensure_nucleus_inside_soma(
    Vcell: np.ndarray,
    Vnuc: np.ndarray,
    margin: float = 0.1,
) -> np.ndarray:
    """
    Ensure all nucleus vertices are inside the actual soma surface.

    Uses a radial/directional check: for each nucleus vertex, finds the
    soma vertex in the most similar direction from center, and ensures
    the nucleus vertex is closer to center than that soma vertex.

    This handles the bumpy GP-sampled soma surface correctly, unlike
    a simple convex hull check.

    Args:
        Vcell: (N, 3) soma surface vertices.
        Vnuc: (N, 3) nucleus surface vertices.
        margin: Safety margin in micrometers (default 0.1 um).

    Returns:
        Adjusted Vnuc array with all vertices inside soma surface.
    """
    soma_center = np.mean(Vcell, axis=0)

    # Precompute soma directions and distances from center
    soma_dirs = Vcell - soma_center
    soma_dists = np.linalg.norm(soma_dirs, axis=1)
    soma_dists_safe = np.maximum(soma_dists, 1e-10)
    soma_dirs_normalized = soma_dirs / soma_dists_safe[:, np.newaxis]

    def get_max_allowed_dist(direction):
        """Get the maximum allowed distance from soma_center in given direction."""
        if np.linalg.norm(direction) < 1e-10:
            return 0.0
        dir_normalized = direction / np.linalg.norm(direction)
        dots = np.dot(soma_dirs_normalized, dir_normalized)
        closest_idx = np.argmax(dots)
        return soma_dists[closest_idx] - margin

    # Iteratively scale nucleus until all vertices are inside
    Vnuc_adjusted = Vnuc.copy()
    nuc_center = np.mean(Vnuc, axis=0)

    for iteration in range(10):  # Max 10 iterations
        # Check all vertices and find the worst violation
        max_ratio = 1.0  # ratio of nuc_dist / allowed_dist
        for i in range(len(Vnuc_adjusted)):
            nuc_dir = Vnuc_adjusted[i] - soma_center
            nuc_dist = np.linalg.norm(nuc_dir)
            if nuc_dist < 1e-6:
                continue

            allowed_dist = get_max_allowed_dist(nuc_dir)
            if allowed_dist > 0:
                ratio = nuc_dist / allowed_dist
                if ratio > max_ratio:
                    max_ratio = ratio

        # If no violations, we're done
        if max_ratio <= 1.0:
            break

        # Scale down the nucleus
        # Use a slightly larger scale factor to converge faster
        scale = 0.95 / max_ratio
        scale = max(scale, 0.8)  # Don't shrink too aggressively in one step

        # Scale relative to nucleus center
        Vnuc_adjusted = nuc_center + (Vnuc_adjusted - nuc_center) * scale

    return Vnuc_adjusted
